const dicts: Record<Locale, Dict> = { en, vi };

function readLocale(): Locale {
  try {
    const v = localStorage.getItem('ld-locale');
    return v === 'en' ? 'en' : 'vi';
  } catch {
    return 'vi';
  }
}

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

export const useLocale = create<LocaleState>((set) => ({
  locale: readLocale(),
  setLocale: (locale) => {
    try {
      localStorage.setItem('ld-locale', locale);
    } catch {
      /* storage unavailable: keep in memory only */
    }
    document.documentElement.lang = locale;
    set({ locale });
  },
}));

export type TFunction = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = dicts[locale][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT(): TFunction {
  const locale = useLocale((s) => s.locale);
  return (key, vars) => translate(locale, key, vars);
}

/** For non-React code (toasts fired from async loops). */
export const t: TFunction = (key, vars) => translate(useLocale.getState().locale, key, vars);
